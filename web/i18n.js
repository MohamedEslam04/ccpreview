const DIR = { en: 'ltr', ar: 'rtl' };
const LOCALE = { en: 'en-US', ar: 'ar-EG' };
const ATTR_KEYS = ['title', 'placeholder', 'aria-label', 'label', 'data-ph']; // data-i18n-<attr>="key"

// First visit: the browser language decides (Arabic -> ar, anything else -> en).
let LANG = /^ar\b/i.test(navigator.language || '') ? 'ar' : 'en';

const isRtl = () => DIR[LANG] === 'rtl';

function setLang(l) {
  LANG = I18N[l] ? l : 'en';
  document.documentElement.lang = LANG;
  document.documentElement.dir = DIR[LANG];
}

function t(key, vars) {
  let s = I18N[LANG][key];
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) return key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

// Plural form for n: key.one (n = 1), key.two (n = 2) if the language has them, else key.other. {n} is filled in.
function tn(key, n, vars) {
  const d = I18N[LANG];
  const form = n === 1 && `${key}.one` in d ? 'one' : n === 2 && `${key}.two` in d ? 'two' : 'other';
  return t(`${key}.${form}`, { n, ...vars });
}

// Fill the markup marked data-i18n (text) and data-i18n-<attr> (attributes) under root.
function applyI18n(root) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  ATTR_KEYS.forEach((a) => {
    root.querySelectorAll(`[data-i18n-${a}]`).forEach((el) => el.setAttribute(a, t(el.getAttribute(`data-i18n-${a}`))));
  });
}
